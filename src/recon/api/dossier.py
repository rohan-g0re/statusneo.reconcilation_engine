#: Backward-compatible alias -- see the note on `RECORD_PROJECTIONS` above.
_PROJECTIONS = RECORD_PROJECTIONS


# Every projection's `simple` must be a subset of what it actually surfaces,
# otherwise the short view silently asks for a field that can never appear.
for _kind, _p in _PROJECTIONS.items():
    _unknown = set(_p.simple) - set(_p.body) - set(_p.row)
    if _unknown:  # pragma: no cover - guard whose job is to never fire
        raise RuntimeError(f"{_kind}: simple names fields it does not project: {sorted(_unknown)}")


# Every kind gets a row.  The previous version skipped unknown kinds with a bare
# `continue`, so four record kinds -- REMITTANCE, BANK_TRANSACTION, REBATE_BATCH
# and a phantom MEDICAL_SUBMISSION_LINE -- vanished from every episode history
# with no error anywhere.  A gap should fail here, at import, not disappear.
_UNPROJECTED = sorted(set(RecordKind) - set(_PROJECTIONS))
if _UNPROJECTED:  # pragma: no cover - a guard whose whole job is to never fire
    raise RuntimeError(
        f"dossier projections missing for {_UNPROJECTED}. Every RecordKind needs one, "
        "or its records disappear from the timeline silently."
    )


def _source(row: sqlite3.Row) -> dict[str, Any]:
    return {
        "file": row["source_file"],
        "line": row["source_line_no"],
        "record_id": row["source_record_id"],
        "norm_id": row["norm_id"],
        "raw_id": row["raw_id"],
    }


def _is_late(received_at: str, occurred_on: str | None) -> bool:
    """Arrival lagging the event by more than a fortnight — the D-2 shape."""
    if not occurred_on:
        return False
    from datetime import date

    try:
        return (date.fromisoformat(received_at[:10]) - date.fromisoformat(occurred_on)).days > 14
    except ValueError:
        return False


def _present(value: Any) -> bool:
    """Absent means no key, null, or an empty collection — not ``False`` or ``0``.

    ``accepted: false`` on an acknowledgment and ``payment_cents: 0`` on a denied
    line are both facts worth stating, so only genuine absence is dropped.
    """
    if value is None:
        return False
    if isinstance(value, (list, dict, str)) and len(value) == 0:
        return False
    return True


def _facts(projection: Projection, row: sqlite3.Row, body: dict[str, Any]) -> dict[str, Any]:
    facts: dict[str, Any] = {}
    for name in projection.row:
        value = row[name]
        if _present(value):
            facts[name] = value
    for name in projection.body:
        value = body.get(name)
        if _present(value):
            facts[name] = value
    return facts


def _record_events(records: list[sqlite3.Row]) -> list[TimelineEvent]:
    events: list[TimelineEvent] = []
    for row in records:
        kind = RecordKind(row["record_kind"])
        projection = _PROJECTIONS[kind]
        body = json.loads(row["canonical"])
        occurred = row["date_of_service"]
        facts = _facts(projection, row, body)
        events.append(
            TimelineEvent(
                at=row["received_at"],
                occurred_on=occurred,
                tag=str(kind),
                facts=facts,
                # Intersected with what is actually present, so `essential` never
                # names a key the consumer cannot find in `facts`.
                essential=tuple(name for name in projection.simple if name in facts),
                source=_source(row),
                late=_is_late(row["received_at"], occurred),
            )
        )
    return events


# ═══ cash ═══════════════════════════════════════════════════════════════════


def _cash_events(allocations: list[sqlite3.Row]) -> list[TimelineEvent]:
    events: list[TimelineEvent] = []
    for row in allocations:
        amount = row["allocated_cents"]
        if amount == 0:
            # A zero allocation is a denied claim line carrying no money. An event
            # saying $0.00 moved implies a payment happened; nothing is truer.
            continue
        bank = json.loads(row["bank_canonical"]) if row["bank_canonical"] else {}
        facts = {
            "direction": "OUT" if amount < 0 else "IN",
            "track": (
                "REBATE" if row["parent_kind"] == str(RecordKind.REBATE_BATCH)
                else "REIMBURSEMENT"
            ),
            # Which basis resolved the link. A TRN02 match and an amount-and-date
            # match are not equally strong claims, so the basis travels with the money.
            "basis": row["basis"],
            "allocated_cents": amount,
        }
        for name in ("ach_trace_number", "trn02"):
            if _present(row[name]):
                facts[name] = row[name]
        if _present(bank.get("posting_date")):
            facts["posting_date"] = bank["posting_date"]

        events.append(
            TimelineEvent(
                at=row["caused_by_received_at"],
                occurred_on=bank.get("posting_date"),
                tag="CASH",
                facts=facts,
                # Which way the money went, on which track, how much, and how
                # confidently it was linked. The trace numbers are identity.
                essential=("direction", "track", "allocated_cents", "basis"),
                source={"ach_trace_number": row["ach_trace_number"], "trn02": row["trn02"]},
            )
        )
    return events


# ═══ verdicts, as transitions ══════════════════════════════════════════════


def _verdict_events(verdicts) -> list[TimelineEvent]:
    """Only the changes.

    An episode evaluated monthly has a dozen identical verdict rows; listing them
    all buries the two that matter.  What an operator wants is the moments the
    answer *moved*.  The full log is returned separately.
    """
    events: list[TimelineEvent] = []
    previous = None
    for verdict in verdicts:
        signature = (
            verdict.reimbursement_verdict_code,
            verdict.rebate_verdict_code,
            verdict.episode_disposition.value,
            tuple(code.value for code in verdict.reasons),
        )
        if previous is not None and signature == previous:
            continue

        facts: dict[str, Any] = {
            "transition": "FIRST" if previous is None else "CHANGED",
            "reimbursement_verdict": verdict.reimbursement_verdict_code,
            "rebate_verdict": verdict.rebate_verdict_code,
            "episode_disposition": verdict.episode_disposition.value,
        }
        reasons = [code.value for code in verdict.reasons]
        if reasons:
            facts["reason_codes"] = reasons
        flags = [flag.code for flag in verdict.cross_track_flags]
        if flags:
            facts["cross_track_flags"] = flags
        if previous is not None:
            facts["previous_reimbursement_verdict"] = previous[0]
            facts["previous_rebate_verdict"] = previous[1]
            facts["previous_disposition"] = previous[2]
        if verdict.reopened_from:
            # Reopened is a flag, not a fourth disposition -- so it is a fact on the
            # transition rather than a different kind of event.
            facts["transition"] = "REOPENED"
            facts["reopened_from"] = verdict.reopened_from.value
            if _present(verdict.previously_closed_at):
                facts["previously_closed_at"] = verdict.previously_closed_at

        events.append(
            TimelineEvent(
                at=verdict.cursor_at,
                occurred_on=None,
                tag="VERDICT",
                facts=facts,
                # A verdict is already the short version of itself -- everything on
                # it is the story. Only the `previous_*` fields are context a short
                # view can drop, since the transition label already says it moved.
                essential=tuple(
                    name for name in facts if not name.startswith("previous_")
                ),
            )
        )
        previous = signature
    return events
